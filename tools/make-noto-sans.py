#!/usr/bin/env python3
"""Regenerate Elm OS's Noto Sans glyphs: the proportional font the UI uses.

Noto Sans Regular (https://notofonts.github.io, SIL Open Font License 1.1, see
host/common/src/noto-sans-OFL.txt) is drawn with antialiasing at each size in SIZES,
so the UI never scales pixels up, and packed into the texture atlas around the
pixel font. It writes:

  host/common/src/noto_sans.rle   the glyphs' coverage, run-length coded (see atlas.rs)
  elm/src/NotoSans.elm            where each glyph is, its offsets and advance, and kerning

    curl -LO https://raw.githubusercontent.com/notofonts/notofonts.github.io/main/fonts/NotoSans/hinted/ttf/NotoSans-Regular.ttf
    python3 tools/make-noto-sans.py NotoSans-Regular.ttf

Needs Pillow with FreeType and Raqm (for kerning), and the hinted Noto Sans above. The output is checked in, so
building Elm OS doesn't.
"""
import os
import sys

# Full hinting: FreeType's older TrueType interpreter (v35) runs the font's hints in
# both directions, so vertical stems land on whole pixels. The default (v40) only
# hints vertically, which leaves stems smeared over two columns at 16 px. FreeType
# reads this when Pillow starts it, so it has to be set before the import.
os.environ["FREETYPE_PROPERTIES"] = "truetype:interpreter-version=35"

from PIL import Image, ImageDraw, ImageFont  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ATLAS_W, ATLAS_H = 1024, 512
# The pixel font, cursor and solid block live in the top left 256 x 256.
SIZES = [16, 24, 32, 48]
CHARS = (
    list(range(33, 127))
    + list(range(161, 256))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC]
)
# Kerning is measured once, at a big size, between these, and stored in 1/1000 em.
KERN_CHARS = list(range(33, 127))
KERN_SIZE = 1000
GAP = 1

path = sys.argv[1]
atlas = Image.new("L", (ATLAS_W, ATLAS_H), 0)


def glyph_image(font, ch):
    """The glyph's coverage and where its top left is from the pen (on the baseline)."""
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    w, h = right - left, bottom - top
    if w <= 0 or h <= 0:
        return None, left, top
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    return im, left, top


# Shelf packing, tallest first, into the free parts of the atlas.
regions = [[256, 0, ATLAS_W, 256], [0, 256, ATLAS_W, ATLAS_H]]  # x0, y0, x1, y1
shelves = []  # [region index, y, height, next x]


def place(w, h):
    for s in shelves:
        r = regions[s[0]]
        if h <= s[2] and s[3] + w <= r[2]:
            x = s[3]
            s[3] += w + GAP
            return x, s[1]
    for i, r in enumerate(regions):
        top = max([s[1] + s[2] + GAP for s in shelves if s[0] == i], default=r[1])
        if top + h <= r[3] and r[0] + w <= r[2]:
            shelves.append([i, top, h, r[0] + w + GAP])
            return r[0], top
    sys.exit("make-noto-sans.py: the glyphs don't fit in the atlas")


faces = []
work = []
for size in SIZES:
    # Basic layout: the hinted advances, whole pixels, so stems stay evenly spaced.
    font = ImageFont.truetype(path, size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    glyphs = {}
    for code in [32] + CHARS:
        ch = chr(code)
        im, left, top = glyph_image(font, ch)
        advance = round(font.getlength(ch) * 64)
        glyphs[code] = [0, 0, 0, 0, left, top, advance]
        if im is not None:
            work.append((im.height, im.width, size, code, im))
    faces.append((size, ascent, descent, glyphs))

for h, w, size, code, im in sorted(work, key=lambda g: (-g[0], -g[1])):
    x, y = place(w, h)
    atlas.paste(im, (x, y))
    g = next(f for f in faces if f[0] == size)[3][code]
    g[0:4] = [x, y, w, h]

big = ImageFont.truetype(path, KERN_SIZE, layout_engine=ImageFont.Layout.RAQM)
widths = {c: big.getlength(chr(c), features=["-liga"]) for c in KERN_CHARS}
kerning = []
for a in KERN_CHARS:
    for b in KERN_CHARS:
        pair = big.getlength(chr(a) + chr(b), features=["-liga"])
        k = round((pair - widths[a] - widths[b]) * 1000 / KERN_SIZE)
        if k != 0:
            kerning.append((a, b, k))

# Run-length coding: a 0 byte is followed by how many 0s (1-255) it stands for; any
# other byte is itself.
px = atlas.tobytes()
out = bytearray()
i = 0
while i < len(px):
    if px[i] == 0:
        n = 1
        while n < 255 and i + n < len(px) and px[i + n] == 0:
            n += 1
        out += bytes([0, n])
        i += n
    else:
        out.append(px[i])
        i += 1
with open(os.path.join(ROOT, "host/common/src/noto_sans.rle"), "wb") as f:
    f.write(out)


def elm_char(code):
    return f"'\\u{{{code:04X}}}'"


lines = [
    "module NotoSans exposing (Face, Glyph, faces, kerning)",
    "",
    "{-| Generated by tools/make-noto-sans.py: don't edit by hand.",
    "",
    "Noto Sans Regular (SIL Open Font License 1.1), drawn at each size and packed into the",
    "host's texture atlas (host/common/src/noto\\_sans.rle).",
    "",
    "A glyph is the rectangle `x`, `y`, `w`, `h` of the atlas, drawn `left` pixels right of the pen",
    "and `top` pixels below the baseline (so usually negative). `advance` is in 1/64 pixels.",
    "",
    "-}",
    "",
    "import Dict exposing (Dict)",
    "",
    "",
    "type alias Glyph =",
    "    { x : Int, y : Int, w : Int, h : Int, left : Int, top : Int, advance : Int }",
    "",
    "",
    "type alias Face =",
    "    { size : Int, ascent : Int, descent : Int, glyphs : Dict Char Glyph }",
    "",
    "",
    "g : Int -> Int -> Int -> Int -> Int -> Int -> Int -> Int -> ( Char, Glyph )",
    "g code x y w h left top advance =",
    "    ( Char.fromCode code, { x = x, y = y, w = w, h = h, left = left, top = top, advance = advance } )",
    "",
    "",
    "{-| Smallest first.",
    "-}",
    "faces : List Face",
    "faces =",
]
for n, (size, ascent, descent, glyphs) in enumerate(faces):
    lines.append(("    [ " if n == 0 else "    , ") + f"{{ size = {size}, ascent = {ascent}, descent = {descent}, glyphs =")
    lines.append("        Dict.fromList")
    for m, (code, gl) in enumerate(sorted(glyphs.items())):
        lines.append(("            [ " if m == 0 else "            , ") + "g " + " ".join(str(v) if v >= 0 else f"({v})" for v in [code] + gl))
    lines.append("            ]")
    lines.append("      }")
lines.append("    ]")
lines += [
    "",
    "",
    "{-| How much closer (negative) or further apart two characters go, in 1/1000 em.",
    "-}",
    "kerning : Dict ( Char, Char ) Int",
    "kerning =",
    "    Dict.fromList",
]
for m, (a, b, k) in enumerate(kerning):
    lines.append(("        [ " if m == 0 else "        , ") + f"( ( {elm_char(a)}, {elm_char(b)} ), {k} )")
lines.append("        ]")
with open(os.path.join(ROOT, "elm/src/NotoSans.elm"), "w") as f:
    f.write("\n".join(lines) + "\n")

used = max(s[1] + s[2] for s in shelves)
print(f"{sum(len(f[3]) for f in faces)} glyphs, {len(kerning)} kerning pairs, atlas rows used to {used}, {len(out)} bytes of RLE")
