#!/usr/bin/env python3
"""Regenerate host/font.h, the pixel font in Elm OS's texture atlas.

The font is town-collab's (https://github.com/MartinSStewart/town-collab, MIT,
by Martin Stewart): 10x18 pixel glyphs, 25 to a row, at x=768 y=0 in its
public/texture.png. The glyph order is Sprite.asciiChars there, and
elm/src/Sprite.elm here.

    python3 tools/make-font.py path/to/town-collab/public/texture.png > host/font.h

Needs Pillow. The output is checked in, so building Elm OS doesn't.
"""
import sys

from PIL import Image

X, Y, W, H = 768, 0, 250, 180  # 25 x 10 glyphs of 10 x 18
STRIDE = 32  # bytes per row: 256 bits

im = Image.open(sys.argv[1]).convert("RGBA").crop((X, Y, X + W, Y + H))
px = im.load()
rows = []
for y in range(H):
    row = bytearray(STRIDE)
    for x in range(W):
        if px[x, y][3] > 0:
            row[x // 8] |= 0x80 >> (x % 8)
    rows.append(row)

print("/* Generated by tools/make-font.py from town-collab's texture.png (MIT, Martin Stewart).")
print(" * 1 bit per pixel, most significant bit first, 32 bytes per row. */")
print(f"#define FONT_W {W}")
print(f"#define FONT_H {H}")
print(f"#define FONT_STRIDE {STRIDE}")
print("static const unsigned char font_bits[FONT_H * FONT_STRIDE] = {")
for row in rows:
    print("    " + ",".join(str(b) for b in row) + ",")
print("};")
