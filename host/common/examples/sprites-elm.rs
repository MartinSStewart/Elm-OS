//! Writes elm/src/Sprites.elm: where the host puts each sprite of sprites/ in the texture
//! atlas (common::sprites), for Elm to draw them from. `make` runs it whenever a sprite
//! changes:
//!
//!     cargo run -p common --example sprites-elm -- ../elm/src/Sprites.elm

use common::sprites::{self, Sprite};
use std::fmt::Write;

/// "cursor-arrow" -> "CursorArrow".
fn constructor(name: &str) -> String {
    name.split(['-', '_'])
        .map(|w| {
            let mut c = w.chars();
            c.next().map_or(String::new(), |f| f.to_uppercase().chain(c).collect())
        })
        .collect()
}

fn record(s: &Sprite) -> String {
    let outline = match s.outline {
        Some([x, y]) => format!("Just ( {x}, {y} )"),
        None => "Nothing".into(),
    };
    format!(
        "{{ width = {}, height = {}, hotSpot = ( {}, {} ), fill = ( {}, {} ), outline = {} }}",
        s.width, s.height, s.hot_spot[0], s.hot_spot[1], s.fill[0], s.fill[1], outline
    )
}

fn main() {
    let path = std::env::args().nth(1).expect("usage: sprites-elm OUTPUT.elm");
    let all = sprites::sprites();
    let mut names: Vec<&str> = all.iter().map(|s| s.name.as_str()).collect();
    names.dedup();
    let mut out = String::new();
    out.push_str(
        "module Sprites exposing (Name(..), Sprite, get)

{-| Where each sprite of sprites/ (at the top of the repository) is in the texture
atlas. GENERATED by `make` from those files, the way the host packs them
(host/common/src/sprites.rs, examples/sprites-elm.rs): don't edit this, edit the files.

-}


{-| One sprite: the files NAME.1x.webp and NAME.2x.webp in sprites/.
-}
type Name\n",
    );
    for (i, n) in names.iter().enumerate() {
        writeln!(out, "    {} {}", if i == 0 { "=" } else { "|" }, constructor(n)).unwrap();
    }
    out.push_str(
        "

{-| A sprite at one UI scale, in device pixels: its size, its hot spot (the pixel that
is its position, from sprites/hot-spots.txt), and where in the atlas its fill (its
white parts, drawn in any colour) and its outline (its black parts, if it has any) are:
the top left corner of a rectangle its size.
-}
type alias Sprite =
    { width : Int, height : Int, hotSpot : ( Int, Int ), fill : ( Int, Int ), outline : Maybe ( Int, Int ) }


{-| A sprite for a UI scale: the 2x picture from scale 2 up.
-}
get : Int -> Name -> Sprite
get scale name =
    case name of
",
    );
    for (i, n) in names.iter().enumerate() {
        let at = |scale| all.iter().find(|s| s.name == *n && s.scale == scale).unwrap();
        if i > 0 {
            out.push('\n');
        }
        write!(
            out,
            "        {} ->
            if scale >= 2 then
                {}

            else
                {}
",
            constructor(n),
            record(at(2)),
            record(at(1))
        )
        .unwrap();
    }
    std::fs::write(&path, out).unwrap_or_else(|e| panic!("can't write {path}: {e}"));
}
